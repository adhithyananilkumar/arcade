#!/usr/bin/env node
/**
 * Generates apps/creator/editor/styles/richtext-theme.css — the bridge between
 * reactjs-tiptap-editor's colours and Arcade's theme.
 *
 * Why: the library is styled with shadcn v1 tokens, `hsl(var(--primary))`, and defines its own
 * zinc palette as bare HSL triplets (`--primary: 240 5.9% 10%`) on `.reactjs-tiptap-editor *` and
 * its portals. Outside that scope the same names hold Arcade's complete colours, so the result was
 * split: inside the editor everything was library zinc whatever the theme; in portals that miss the
 * scope (tooltips) `hsl(<oklch>)` was invalid and dropped — dark boxes with invisible text.
 *
 * The fix captures Arcade's colours at :root under private names (`--rt-*`). A custom property
 * stores its *resolved* value and inherits that, so the library's redefinitions deeper in the tree
 * can't reach them. Every library declaration that used a token is re-emitted with the same
 * selector, reading `--rt-*`. Imported after the library's sheet, equal specificity wins.
 * editor-chrome.css reads the same `--rt-*` names for the same reason.
 *
 * Re-run after upgrading reactjs-tiptap-editor:
 *   node scripts/build-richtext-theme.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(join(root, "package.json"));
const libDir = dirname(require.resolve("reactjs-tiptap-editor/style.css"));
const source = readFileSync(join(libDir, "style.css"), "utf8");

/** Where each captured colour comes from. Fallbacks cover tokens a theme may leave undefined. */
const SOURCES = {
  "destructive-foreground": "var(--destructive-foreground, #ffffff)",
  "richtext-text-foreground": "var(--foreground)",
};

/** Captured for editor-chrome.css as well, though the library itself doesn't use them. */
const EXTRA = {
  ink: "var(--ink, #14142b)",
  "on-ink": "var(--on-ink, #ffffff)",
  "n-100": "var(--n-100, #f1f5f9)",
  "n-200": "var(--n-200, #e2e8f0)",
  "n-400": "var(--n-400, #94a3b8)",
  "n-500": "var(--n-500, #64748b)",
  "n-700": "var(--n-700, #334155)",
  "n-800": "var(--n-800, #1e293b)",
  "n-900": "var(--n-900, #0f172a)",
};

const used = new Set();
function token(name) {
  used.add(name);
  return `var(--rt-${name})`;
}

function convert(value) {
  return value
    .replace(/hsl\(var\(--([a-z-]+)\)\s*\/\s*([\d.]+)\)/g, (_, name, alpha) => {
      const pct = Math.round(parseFloat(alpha) * 100);
      return `color-mix(in oklab, ${token(name)} ${pct}%, transparent)`;
    })
    .replace(/hsl\(var\(--([a-z-]+)\)\)/g, (_, name) => token(name));
}

/**
 * Declarations that only "worked" because they were broken. The editor root asks for an opaque
 * page background; Arcade's editor is chromeless over a frosted canvas, so it stays clear.
 */
const KEEP_TRANSPARENT = [{ selector: /^\.reactjs-tiptap-editor$/, property: "background-color" }];

const rules = [];
const ruleRe = /([^{}]+)\{([^{}]*)\}/g;
let match;
while ((match = ruleRe.exec(source))) {
  const selector = match[1].trim();
  if (selector.startsWith("@")) continue;
  const declarations = match[2]
    .split(";")
    .map((d) => d.trim())
    .filter((d) => /hsl\(var\(--/.test(d))
    .map((d) => {
      const property = d.split(":")[0].trim();
      const transparent = KEEP_TRANSPARENT.some((k) => k.selector.test(selector) && k.property === property);
      return transparent ? `${property}:transparent` : convert(d);
    });
  if (declarations.length) rules.push(`${selector}{${declarations.join(";")}}`);
}

const captured = [
  ...[...used].sort().map((name) => `  --rt-${name}: ${SOURCES[name] ?? `var(--${name})`};`),
  ...Object.entries(EXTRA).map(([name, value]) => `  --rt-${name}: ${value};`),
];

const output = [
  "/* GENERATED by scripts/build-richtext-theme.mjs — do not edit by hand.",
  " * Re-points reactjs-tiptap-editor's colours at Arcade's theme. See the script for why.",
  ` * ${rules.length} rules. */`,
  ":root {",
  ...captured,
  "}",
  ...rules,
  "",
].join("\n");

const target = join(root, "apps/creator/editor/styles/richtext-theme.css");
writeFileSync(target, output);
console.log(`wrote ${rules.length} rules (${used.size} tokens captured) to ${target}`);
